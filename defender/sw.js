self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('message', e => { if (e.data === 'warm') e.waitUntil(caches.open(CACHE).then(async c => { for (const u of LATER) { if (await c.match(u)) continue; try { const r = await fetch(u); if (r.ok) await c.put(u, r); } catch (err) {} } })); });
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  // the page and the list of recorded voices: network first so a new build or new clips show up, cache when offline
  if (req.mode === 'navigate' || req.url.endsWith('/index.html') || req.url.endsWith('/voice/index.json')) { e.respondWith(fetch(req).then(r => { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); return r; }).catch(() => caches.match(req).then(r => r || caches.match('./index.html')))); return; }
  // everything else (art, fonts, optional PNG drop-ins): cache first, then network, and remember what came back
  if (req.headers.has('range') || req.url.includes('/music/')) return; // music streams in pieces; let the browser handle it
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(r => { if (r && (r.ok || r.type === 'opaque')) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); } return r; }).catch(() => hit)));
});
